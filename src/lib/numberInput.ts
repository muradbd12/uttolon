// টাকার পরিমাণ / সংখ্যার ঘরে বাংলা ও ইংরেজি — দুই ধরনের সংখ্যাই টাইপ করার
// সুবিধা দিতে এই হেল্পার ব্যবহার হয়। আগে এই ঘরগুলো type="number" ছিল,
// যেটাতে বাংলা সংখ্যা (০-৯) লেখা যেত না এবং মোবাইলে অনেক সময় শুধু
// +/- স্পিনার বাটন দেখাত। এখন এই ঘরগুলো সাধারণ টেক্সট ঘর, আর এই ফাংশনটা
// ব্যবহারকারী যা-ই টাইপ করুন (বাংলা/ইংরেজি সংখ্যা), সেটাকে হিসাবের জন্য
// ইংরেজি সংখ্যায় বদলে দেয়।

const bnToEnDigits: Record<string, string> = {
  "০": "0", "১": "1", "২": "2", "৩": "3", "৪": "4",
  "৫": "5", "৬": "6", "৭": "7", "৮": "8", "৯": "9",
};

/** যেকোনো ইনপুট স্ট্রিং থেকে বাংলা সংখ্যা ইংরেজিতে বদলে, শুধু সংখ্যাগুলো রেখে বাকি সব বাদ দেয়। */
export function toEnglishDigits(value: string): string {
  return value
    .split("")
    .map((ch) => bnToEnDigits[ch] ?? ch)
    .join("")
    .replace(/[^0-9]/g, "");
}
